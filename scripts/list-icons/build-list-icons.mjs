#!/usr/bin/env node
/**
 * Builds the icon set that lead sources, divisions, interest categories, price-offer
 * categories and income/expense categories can carry (see src/utils/listIcons.ts).
 *
 * The icons are Twemoji (https://github.com/jdecked/twemoji, CC BY 4.0), flat colour
 * emoji drawn as SVG. We ship them as pictures, never as emoji characters: Windows has
 * no flag glyphs, so a 🇸🇰 typed into a label shows up there as the letters "SK".
 *
 * Usage (the package is only needed while regenerating, it is not a dependency):
 *
 *   npm pack @iconify-json/twemoji        # in any scratch folder
 *   tar xzf iconify-json-twemoji-*.tgz
 *   node scripts/list-icons/build-list-icons.mjs <scratch>/package/icons.json
 *
 * Writes:
 *   public/list-icons.svg                  one <symbol> per icon, id = the Twemoji name
 *   src/utils/listIconCatalog.generated.ts the groups the picker shows + a cache-busting version
 *
 * Ids are stored in settings, so never rename or drop one that has shipped; only add.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");

/** The picker's groups, in display order. Business-relevant only: no faces. */
const GROUPS = {
  flags: [
    "flag-slovakia", "flag-hungary", "flag-czechia", "flag-austria", "flag-poland", "flag-germany",
    "flag-ukraine", "flag-romania", "flag-croatia", "flag-slovenia", "flag-italy",
    "flag-united-kingdom", "flag-united-states", "flag-european-union",
  ],
  channels: [
    "globe-with-meridians", "desktop-computer", "laptop", "mobile-phone", "telephone-receiver", "e-mail",
    "envelope", "speech-balloon", "megaphone", "loudspeaker", "newspaper", "television", "radio", "camera",
    "magnifying-glass-tilted-left", "link", "handshake", "bust-in-silhouette", "busts-in-silhouette",
    "office-building", "house", "department-store", "convenience-store", "shopping-cart", "shopping-bags",
    "automobile", "round-pushpin", "world-map", "calendar", "ticket",
  ],
  business: [
    "briefcase", "money-bag", "euro-banknote", "dollar-banknote", "coin", "credit-card", "receipt", "bank",
    "chart-increasing", "chart-decreasing", "bar-chart", "clipboard", "page-facing-up", "file-folder",
    "balance-scale", "package", "delivery-truck", "gear", "wrench", "hammer", "toolbox", "hammer-and-wrench",
    "light-bulb", "electric-plug", "high-voltage", "fuel-pump", "droplet", "construction", "brick", "wood",
    "window", "door", "bed", "couch-and-lamp", "bathtub", "artist-palette", "straight-ruler",
    "triangular-ruler", "graduation-cap", "books", "hospital", "pill", "fork-and-knife", "hot-beverage",
    "airplane", "hotel", "seedling", "deciduous-tree", "sun",
  ],
  symbols: [
    "star", "glowing-star", "sparkles", "fire", "gem-stone", "trophy", "crown", "wrapped-gift", "bell",
    "red-heart", "check-mark-button", "warning", "prohibited", "hourglass-not-done", "rocket", "label",
    "bookmark", "red-circle", "orange-circle", "yellow-circle", "green-circle", "blue-circle",
    "purple-circle", "brown-circle", "black-circle", "white-circle",
  ],
};

const source = process.argv[2];
if (!source) {
  console.error("Usage: node scripts/list-icons/build-list-icons.mjs <path to @iconify-json/twemoji icons.json>");
  process.exit(1);
}
const set = JSON.parse(readFileSync(source, "utf8"));
const size = set.width || 36;

const symbols = [];
const missing = [];
const seen = new Set();
for (const ids of Object.values(GROUPS)) {
  for (const id of ids) {
    if (seen.has(id)) throw new Error(`Duplicate icon id: ${id}`);
    seen.add(id);
    const icon = set.icons[id];
    if (!icon) { missing.push(id); continue; }
    const w = icon.width || size;
    const h = icon.height || size;
    symbols.push(`<symbol id="${id}" viewBox="0 0 ${w} ${h}">${icon.body}</symbol>`);
  }
}
if (missing.length) {
  console.error(`Not in the Twemoji set: ${missing.join(", ")}`);
  process.exit(1);
}

const sprite =
  `<svg xmlns="http://www.w3.org/2000/svg">` +
  `<!-- Twemoji by Twitter, Inc and other contributors, https://github.com/jdecked/twemoji, CC BY 4.0 (https://creativecommons.org/licenses/by/4.0/). Generated by scripts/list-icons/build-list-icons.mjs. -->` +
  symbols.join("") +
  `</svg>\n`;
writeFileSync(join(ROOT, "public", "list-icons.svg"), sprite);

const version = createHash("sha1").update(sprite).digest("hex").slice(0, 10);
const catalog = `// GENERATED by scripts/list-icons/build-list-icons.mjs. Do not edit by hand.
// Icons: Twemoji (https://github.com/jdecked/twemoji), CC BY 4.0. Sprite: public/list-icons.svg.

export const LIST_ICON_GROUPS = ${JSON.stringify(
  Object.entries(GROUPS).map(([id, icons]) => ({ id, icons })),
  null,
  2,
)} as const;

/** Changes whenever the sprite does, so browsers never keep a stale copy. */
export const LIST_ICON_SPRITE_VERSION = "${version}";
`;
writeFileSync(join(ROOT, "src", "utils", "listIconCatalog.generated.ts"), catalog);

console.log(`Wrote ${symbols.length} icons (${(sprite.length / 1024).toFixed(1)} KB), version ${version}.`);
