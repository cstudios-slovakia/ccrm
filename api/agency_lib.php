    function ccrm_agency_log_timeline(
        PDO $pdo,
        string $workerId,
        string $eventType,
        string $title,
        string $description = '',
        array $meta = [],
        ?string $occurredAt = null,
        ?string $createdBy = null
    ): array {
        $allowed = ['stage_change', 'contact', 'placement', 'sick_leave', 'compliance', 'note', 'work_log'];
        if (!in_array($eventType, $allowed, true)) {
            $eventType = 'note';
        }
        $id = ccrm_agency_uid('agtl');
        $ts = $occurredAt && preg_match('/^\d{4}-\d{2}-\d{2}/', $occurredAt)
            ? (strlen($occurredAt) === 10 ? ($occurredAt . ' 09:00:00') : substr(str_replace('T', ' ', $occurredAt), 0, 19))
            : date('Y-m-d H:i:s');
        $metaJson = !empty($meta) ? json_encode($meta, JSON_UNESCAPED_UNICODE | JSON_INVALID_UTF8_SUBSTITUTE) : null;
        $stmt = $pdo->prepare(
            "INSERT INTO `agency_timeline_events` (`id`, `worker_id`, `event_type`, `title`, `description`, `meta_json`, `occurred_at`, `created_by`)
             VALUES (?, ?, ?, ?, ?, ?, ?, ?)"
        );
        $stmt->execute([$id, $workerId, $eventType, $title, $description, $metaJson, $ts, $createdBy]);
        return [
            'id' => $id,
            'workerId' => $workerId,
            'eventType' => $eventType,
            'title' => $title,
            'description' => $description,
            'meta' => $meta ?: (object)[],
            'occurredAt' => $ts,
            'createdBy' => (string)($createdBy ?? ''),
        ];
    }

    function ccrm_agency_is_period_paid(PDO $pdo, string $workerId, string $workDate): bool {
        if (!preg_match('/^(\d{4}-\d{2})/', $workDate, $m)) {
            return false;
        }
        $ym = $m[1];
        $stmt = $pdo->prepare("SELECT `status` FROM `agency_payments` WHERE `worker_id` = ? AND `period_ym` = ? LIMIT 1");
        $stmt->execute([$workerId, $ym]);
        return $stmt->fetchColumn() === 'paid';
    }

    function ccrm_agency_calculate_payment_data(PDO $pdo, string $workerId, string $periodYm, ?array $settings = null): array {
        if ($settings === null) {
            $settings = ccrm_agency_load_settings($pdo);
        }
        $workerStmt = $pdo->prepare("SELECT * FROM `agency_workers` WHERE `id` = ? LIMIT 1");
        $workerStmt->execute([$workerId]);
        $worker = $workerStmt->fetch(PDO::FETCH_ASSOC);
        if (!$worker) {
            throw new \RuntimeException('Worker not found');
        }

        $tplById = [];
        foreach ($settings['shiftTemplates'] ?? [] as $tpl) {
            if (!empty($tpl['id'])) {
                $tplById[(string)$tpl['id']] = $tpl;
            }
        }
        $otMult = floatval($settings['overtimeMultiplier'] ?? 1.25);

        $plStmt = $pdo->prepare(
            "SELECT * FROM `agency_placements`
             WHERE `worker_id` = ?
             ORDER BY (`status` = 'active') DESC, `start_date` DESC"
        );
        $plStmt->execute([$workerId]);
        $placements = $plStmt->fetchAll(PDO::FETCH_ASSOC);
        $placementById = [];
        foreach ($placements as $pl) {
            $placementById[(string)$pl['id']] = $pl;
        }
        $primaryPlacement = $placements[0] ?? null;

        $startDate = $periodYm . '-01';
        $endDate = date('Y-m-t', strtotime($startDate));
        $shStmt = $pdo->prepare(
            "SELECT * FROM `agency_shifts`
             WHERE `worker_id` = ? AND `work_date` BETWEEN ? AND ?
             ORDER BY `work_date` ASC"
        );
        $shStmt->execute([$workerId, $startDate, $endDate]);
        $shifts = $shStmt->fetchAll(PDO::FETCH_ASSOC);

        $regularHours = 0.0;
        $overtimeHours = 0.0;
        $sickDays = 0.0;
        $basePay = 0.0;
        $billableTotal = 0.0;
        $companyClientId = $primaryPlacement ? (string)$primaryPlacement['company_client_id'] : null;
        $placementId = $primaryPlacement ? (string)$primaryPlacement['id'] : null;

        foreach ($shifts as $sh) {
            $status = (string)($sh['status'] ?? 'scheduled');
            if ($status === 'sick') {
                $sickDays += 1.0;
                continue;
            }
            if ($status === 'absent') {
                continue;
            }
            $h = floatval($sh['hours'] ?? 0);
            $ot = floatval($sh['overtime_hours'] ?? 0);
            if ($status === 'holiday' && $h <= 0 && $ot <= 0) {
                continue;
            }
            $pl = (!empty($sh['placement_id']) && isset($placementById[$sh['placement_id']]))
                ? $placementById[$sh['placement_id']]
                : $primaryPlacement;
            $payRate = $pl && floatval($pl['pay_rate']) > 0 ? floatval($pl['pay_rate']) : floatval($worker['default_pay_rate'] ?? 0);
            $billRate = $pl && floatval($pl['bill_rate']) > 0 ? floatval($pl['bill_rate']) : floatval($worker['default_bill_rate'] ?? 0);
            $tpl = (!empty($sh['shift_template_id']) && isset($tplById[$sh['shift_template_id']]))
                ? $tplById[$sh['shift_template_id']]
                : null;
            $payMult = $tpl ? floatval($tpl['payMultiplier'] ?? 1.0) : 1.0;
            $billMult = $tpl ? floatval($tpl['billMultiplier'] ?? 1.0) : 1.0;
            if ($status === 'holiday') {
                $holMult = floatval($settings['holidayMultiplier'] ?? 1.5);
                $payMult = max($payMult, $holMult);
                $billMult = max($billMult, $holMult);
            }

            $regularHours += $h;
            $overtimeHours += $ot;
            $basePay += ($h * $payRate * $payMult) + ($ot * $payRate * $otMult);
            $billableTotal += ($h * $billRate * $billMult) + ($ot * $billRate * $otMult);
            if (!$companyClientId && !empty($sh['company_client_id'])) {
                $companyClientId = (string)$sh['company_client_id'];
            }
        }

        // Preserve any custom earnings/deductions already saved on this period row.
        $existingStmt = $pdo->prepare("SELECT * FROM `agency_payments` WHERE `worker_id` = ? AND `period_ym` = ? LIMIT 1");
        $existingStmt->execute([$workerId, $periodYm]);
        $existing = $existingStmt->fetch(PDO::FETCH_ASSOC);
        $items = [];
        if ($existing && !empty($existing['items_json'])) {
            $decoded = json_decode((string)$existing['items_json'], true);
            if (is_array($decoded)) {
                $items = array_values(array_filter($decoded, static fn ($it) => is_array($it) && ($it['id'] ?? '') !== 'base-shifts'));
            }
        }

        $extraEarnings = 0.0;
        $deductionsTotal = 0.0;
        foreach ($items as $it) {
            $amt = floatval($it['amount'] ?? 0);
            if (($it['kind'] ?? 'earning') === 'deduction') {
                $deductionsTotal += $amt;
            } else {
                $extraEarnings += $amt;
            }
        }
        $grossPay = round($basePay + $extraEarnings, 2);
        $deductionsTotal = round($deductionsTotal, 2);
        $netPay = round(max(0, $grossPay - $deductionsTotal), 2);
        $billableTotal = round($billableTotal, 2);

        return [
            'workerId' => $workerId,
            'placementId' => $existing['placement_id'] ?? $placementId,
            'companyClientId' => $existing['company_client_id'] ?? $companyClientId,
            'periodYm' => $periodYm,
            'regularHours' => round($regularHours, 2),
            'overtimeHours' => round($overtimeHours, 2),
            'sickDays' => round($sickDays, 1),
            'basePay' => round($basePay, 2),
            'items' => $items,
            'grossPay' => $grossPay,
            'deductionsTotal' => $deductionsTotal,
            'netPay' => $netPay,
            'paidAmount' => $existing ? floatval($existing['paid_amount']) : 0.0,
            'billableTotal' => $billableTotal,
            'currency' => (string)($primaryPlacement['currency'] ?? $worker['currency'] ?? $settings['defaultCurrency'] ?? 'EUR'),
            'status' => $existing['status'] ?? 'draft',
            'paidAt' => $existing['paid_at'] ?? null,
            'financialRecordId' => $existing['financial_record_id'] ?? null,
            'notes' => (string)($existing['notes'] ?? ''),
        ];
    }

    function ccrm_agency_sync_financial_expense(PDO $pdo, array $paymentRow, string $workerName, array $settings): ?string {
        if (empty($settings['autoCreateExpense'])) {
            return $paymentRow['financial_record_id'] ?? null;
        }
        if (!ccrm_table_exists($pdo, 'financial_records')) {
            return $paymentRow['financial_record_id'] ?? null;
        }
        $paymentId = (string)$paymentRow['id'];
        $frId = !empty($paymentRow['financial_record_id'])
            ? (string)$paymentRow['financial_record_id']
            : ('fr-ag-' . $paymentId);
        $netPay = round(floatval($paymentRow['net_pay'] ?? 0), 2);
        $paidAmount = round(floatval($paymentRow['paid_amount'] ?? 0), 2);
        $status = (string)($paymentRow['status'] ?? 'draft');
        $frStatus = ($status === 'paid') ? 'paid' : ($paidAmount > 0 ? 'partially_paid' : 'pending');
        $periodYm = (string)$paymentRow['period_ym'];
        $issueDate = $periodYm . '-01';
        $dueDate = $periodYm . '-15';
        $currency = strtoupper(trim((string)($paymentRow['currency'] ?? $settings['defaultCurrency'] ?? 'EUR'))) ?: 'EUR';
        $paidDate = ($frStatus === 'paid')
            ? (!empty($paymentRow['paid_at']) ? (string)$paymentRow['paid_at'] : date('Y-m-d'))
            : null;
        $catId = !empty($settings['defaultExpenseCategoryId']) ? (string)$settings['defaultExpenseCategoryId'] : 'fc-exp-payroll';
        $catExists = $pdo->prepare("SELECT COUNT(*) FROM `financial_categories` WHERE `id` = ?");
        $catExists->execute([$catId]);
        $resolvedCatId = ((int)$catExists->fetchColumn() > 0) ? $catId : null;

        $title = trim('Agency Payout: ' . $workerName . ' (' . $periodYm . ')');
        $ins = $pdo->prepare(
            "INSERT INTO `financial_records` (`id`, `type`, `subtype`, `title`, `category_id`, `amount_planned`, `amount_real`, `currency`, `status`, `issue_date`, `due_date`, `paid_date`, `description`)
             VALUES (?, 'expense', 'salary', ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
             ON DUPLICATE KEY UPDATE
               `title` = VALUES(`title`),
               `category_id` = VALUES(`category_id`),
               `amount_planned` = VALUES(`amount_planned`),
               `amount_real` = VALUES(`amount_real`),
               `currency` = VALUES(`currency`),
               `status` = VALUES(`status`),
               `due_date` = VALUES(`due_date`),
               `paid_date` = VALUES(`paid_date`)"
        );
        $ins->execute([
            $frId,
            $title,
            $resolvedCatId,
            $netPay,
            $frStatus === 'paid' ? $netPay : $paidAmount,
            $currency,
            $frStatus,
            $issueDate,
            $dueDate,
            $paidDate,
            'Synced from Agency Workforce Leasing payout #' . $paymentId,
        ]);
        if (($paymentRow['financial_record_id'] ?? '') !== $frId) {
            $pdo->prepare("UPDATE `agency_payments` SET `financial_record_id` = ? WHERE `id` = ?")->execute([$frId, $paymentId]);
        }
        return $frId;
    }
