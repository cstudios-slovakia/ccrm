    function ccrm_agency_private_dir(): string {
        $dir = ccrm_uploads_dir() . 'private/agency/';
        if (!is_dir($dir)) {
            @mkdir($dir, 0750, true);
        }
        $htaccess = $dir . '.htaccess';
        $marker = '# Generated by CCRM — do not remove. Private agency worker documents. Guard version: 1';
        $existing = is_file($htaccess) ? (string)@file_get_contents($htaccess) : '';
        if (strpos($existing, $marker) === false) {
            $guard = $marker . "\n" . <<<'HTACCESS'
# Served only through api/agency_file.php, after a permission check.
<Files "*">
    <IfModule mod_authz_core.c>
        Require all denied
    </IfModule>
    <IfModule !mod_authz_core.c>
        Order allow,deny
        Deny from all
    </IfModule>
</Files>
<IfModule mod_authz_core.c>
    Require all denied
</IfModule>
<IfModule !mod_authz_core.c>
    Order allow,deny
    Deny from all
</IfModule>
php_flag engine off
HTACCESS
            . "\n";
            @file_put_contents($htaccess, $guard);
        }
        return $dir;
    }

    function ccrm_agency_private_new_name(string $originalName): string {
        $ext = strtolower((string)pathinfo($originalName, PATHINFO_EXTENSION));
        $extClean = preg_replace('/[^a-z0-9]/', '', $ext);
        $token = bin2hex(random_bytes(16));
        return $extClean !== '' ? ($token . '.' . $extClean) : $token;
    }

    function ccrm_agency_private_path(string $storageName): ?string {
        $prefix = ccrm_agency_private_prefix();
        if (strpos($storageName, $prefix) === 0) {
            $storageName = substr($storageName, strlen($prefix));
        }
        $clean = basename($storageName);
        if ($clean === '' || $clean === '.' || $clean === '..' || strpos($storageName, '/') !== false) {
            return null;
        }
        $full = ccrm_agency_private_dir() . $clean;
        return is_file($full) ? $full : null;
    }

