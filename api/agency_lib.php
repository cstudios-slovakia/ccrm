    function ccrm_agency_normalize_settings($raw): array {
        $defaults = ccrm_agency_default_settings();
        if (!is_array($raw)) {
            return $defaults;
        }
        $out = $defaults;
        if (!empty($raw['stages']) && is_array($raw['stages'])) {
            $out['stages'] = array_values($raw['stages']);
        }
        if (!empty($raw['checklistItems']) && is_array($raw['checklistItems'])) {
            $out['checklistItems'] = array_values($raw['checklistItems']);
        }
        if (!empty($raw['shiftTemplates']) && is_array($raw['shiftTemplates'])) {
            $out['shiftTemplates'] = array_values($raw['shiftTemplates']);
        }
        if (isset($raw['holidayCountry']) && in_array($raw['holidayCountry'], ['SK', 'HU'], true)) {
            $out['holidayCountry'] = $raw['holidayCountry'];
        }
        if (isset($raw['overtimeMultiplier']) && is_numeric($raw['overtimeMultiplier'])) {
            $out['overtimeMultiplier'] = max(1.0, min(5.0, floatval($raw['overtimeMultiplier'])));
        }
        if (isset($raw['holidayMultiplier']) && is_numeric($raw['holidayMultiplier'])) {
            $out['holidayMultiplier'] = max(1.0, min(5.0, floatval($raw['holidayMultiplier'])));
        }
        if (isset($raw['defaultCurrency']) && is_string($raw['defaultCurrency']) && trim($raw['defaultCurrency']) !== '') {
            $out['defaultCurrency'] = strtoupper(substr(trim($raw['defaultCurrency']), 0, 10));
        }
        if (array_key_exists('autoCreateExpense', $raw)) {
            $out['autoCreateExpense'] = (bool)$raw['autoCreateExpense'];
        }
        if (isset($raw['defaultExpenseCategoryId']) && is_string($raw['defaultExpenseCategoryId'])) {
            $out['defaultExpenseCategoryId'] = trim($raw['defaultExpenseCategoryId']);
        }
        if (!empty($raw['profileSchema']) && is_array($raw['profileSchema'])) {
            $out['profileSchema'] = array_values($raw['profileSchema']);
        }
        return $out;
    }

    function ccrm_agency_load_settings(PDO $pdo): array {
        try {
            $raw = $pdo->query("SELECT `value` FROM `system_settings` WHERE `key` = 'AGENCY_SETTINGS' LIMIT 1")->fetchColumn();
            if (is_string($raw) && $raw !== '') {
                $decoded = json_decode($raw, true);
                if (is_array($decoded)) {
                    return ccrm_agency_normalize_settings($decoded);
                }
            }
        } catch (\Throwable $e) {
            // Fall through to defaults.
        }
        return ccrm_agency_default_settings();
    }

    function ccrm_agency_save_settings(PDO $pdo, array $cfg): array {
        $normalized = ccrm_agency_normalize_settings($cfg);
        $encoded = json_encode($normalized, JSON_UNESCAPED_UNICODE | JSON_INVALID_UTF8_SUBSTITUTE);
        $stmt = $pdo->prepare("INSERT INTO `system_settings` (`key`, `value`) VALUES ('AGENCY_SETTINGS', ?) ON DUPLICATE KEY UPDATE `value` = VALUES(`value`)");
        $stmt->execute([$encoded]);
        return $normalized;
    }

    function ccrm_agency_is_module_enabled(PDO $pdo): bool {
        try {
            $raw = $pdo->query("SELECT `value` FROM `system_settings` WHERE `key` = 'INTEGRATIONS_CONFIG' LIMIT 1")->fetchColumn();
            if (!is_string($raw) || $raw === '') {
                return false;
            }
            $cfg = json_decode($raw, true);
            $disabled = is_array($cfg['disabledModules'] ?? null) ? $cfg['disabledModules'] : [];
            return !in_array('agency', $disabled, true);
        } catch (\Throwable $e) {
            return false;
        }
    }

    function ccrm_agency_uid(string $prefix = 'ag'): string {
