<?php
/**
 * Private employee documents (contracts and the like).
 *
 * They used to be stored in uploads/ under a guessable name
 * (`emp_contract_<Date.now()>_<original name>`), and uploads/.htaccess grants
 * everyone read access, so a contract was one URL away from anybody on the
 * internet. They now live in uploads/private/employees/ under a random name,
 * behind a deny-all guard, and are streamed by api/employee_file.php after a
 * permission check. The original file name is kept only in
 * `employees.files_json`.
 *
 * A stored document is addressed by its STORAGE KEY, `private/employees/<32 hex>.<ext>`,
 * which is what an employee file record keeps in its `url`. A key never comes from a
 * request: the endpoint looks the file up by id inside the employee's own record.
 */

require_once __DIR__ . '/auth.php';

if (!function_exists('ccrm_employee_private_prefix')) {

    /** Storage-key prefix of every private employee document. */
    function ccrm_employee_private_prefix(): string {
        return 'private/employees/';
    }

    /**
     * First line of the generated guard. BUMP THE VERSION whenever the guard
     * changes (same reasoning as ccrm_uploads_guard_marker()).
     */
    function ccrm_employee_private_guard_marker(): string {
        return '# Generated by CCRM — do not remove. Private employee documents. Guard version: 1';
    }

    /**
     * The guard: nothing here is ever served by the web server. The parent
     * uploads/.htaccess re-grants access inside a <Files "*"> section, and Apache
     * applies <Files> sections from every level in order, so the deny has to be a
     * <Files> section as well or the parent's grant would win.
     */
    function ccrm_employee_private_guard_contents(): string {
        return ccrm_employee_private_guard_marker() . "\n" . <<<'HTACCESS'
# Served only through api/employee_file.php, after a permission check.
<Files "*">
    <IfModule mod_authz_core.c>
        Require all denied
    </IfModule>
    <IfModule !mod_authz_core.c>
        Order allow,deny
        Deny from all
    </IfModule>
</Files>
<IfModule mod_authz_core.c>
    Require all denied
</IfModule>
<IfModule !mod_authz_core.c>
    Order allow,deny
    Deny from all
</IfModule>
php_flag engine off
HTACCESS
        . "\n";
    }

    /**
     * Absolute path of uploads/private/employees/ WITH a trailing slash, created
     * on demand together with its guard (and a guard on uploads/private/ itself).
     */
    function ccrm_employee_private_dir(): string {
        $base = ccrm_uploads_dir() . 'private/';
        $dir = $base . 'employees/';
        foreach ([$base, $dir] as $d) {
            if (!is_dir($d)) {
                @mkdir($d, 0775, true);
            }
            if (is_dir($d)) {
                $guard = $d . '.htaccess';
                $existing = @file_get_contents($guard);
                if ($existing === false || strpos($existing, ccrm_employee_private_guard_marker()) === false) {
                    @file_put_contents($guard, ccrm_employee_private_guard_contents());
                }
            }
        }
        return $dir;
    }

    /** A random, extension-preserving storage name: 32 hex characters plus a safe extension. */
    function ccrm_employee_private_new_name(string $originalName): string {
        $ext = strtolower(pathinfo($originalName, PATHINFO_EXTENSION));
        $ext = preg_replace('/[^a-z0-9]/', '', $ext);
        if ($ext === '' || strlen($ext) > 10) {
            $ext = 'bin';
        }
        return bin2hex(random_bytes(16)) . '.' . $ext;
    }

    /** Is this a well-formed storage key (nothing but our own naming scheme)? */
    function ccrm_employee_private_key_ok(string $key): bool {
        $prefix = ccrm_employee_private_prefix();
        if (strncmp($key, $prefix, strlen($prefix)) !== 0) {
            return false;
        }
        return preg_match('/^[a-f0-9]{32}\.[a-z0-9]{1,10}$/', substr($key, strlen($prefix))) === 1;
    }

    /** Absolute path of a stored document, or null when the key is malformed or the file is missing. */
    function ccrm_employee_private_path(string $key): ?string {
        if (!ccrm_employee_private_key_ok($key)) {
            return null;
        }
        $path = ccrm_employee_private_dir() . substr($key, strlen(ccrm_employee_private_prefix()));
        $real = realpath($path);
        $realBase = realpath(ccrm_employee_private_dir());
        if ($real === false || $realBase === false || strncmp($real, $realBase, strlen($realBase)) !== 0 || !is_file($real)) {
            return null;
        }
        return $real;
    }

    /** Remove a stored document (best effort). */
    function ccrm_employee_private_delete(string $key): void {
        $path = ccrm_employee_private_path($key);
        if ($path !== null) {
            @unlink($path);
        }
    }

    /**
     * Delete the given storage keys unless some employee record still references one.
     * Called after a sync has COMMITTED, so a rolled-back save never costs a document.
     *
     * @param string[] $keys
     */
    function ccrm_employee_private_gc(\PDO $pdo, array $keys): void {
        foreach (array_unique($keys) as $key) {
            if (!ccrm_employee_private_key_ok($key)) {
                continue;
            }
            try {
                $ref = $pdo->prepare("SELECT 1 FROM `employees` WHERE `files_json` LIKE ? LIMIT 1");
                $ref->execute(['%' . basename($key) . '%']);
                if ($ref->fetchColumn() === false) {
                    ccrm_employee_private_delete($key);
                }
            } catch (\Throwable $e) {
                error_log('[ccrm employee files] gc skipped for ' . $key . ': ' . $e->getMessage());
            }
        }
    }

    /** The storage key an employee file record points at, or null when it is not a private one. */
    function ccrm_employee_file_key(array $file): ?string {
        $key = (string)($file['url'] ?? $file['path'] ?? '');
        return ccrm_employee_private_key_ok($key) ? $key : null;
    }

    /**
     * Move every employee document still sitting in the public uploads directory into
     * the private one and rewrite the stored path. Idempotent: a record that already
     * points at a private key is left alone. A record whose file is missing keeps its
     * entry and is logged. Cheap to call on every request (one indexed-free LIKE on a
     * handful of rows that stops matching once everything has moved).
     *
     * @return int number of files moved
     */
    function ccrm_migrate_employee_files_private(\PDO $pdo): int {
        $moved = 0;
        try {
            $rows = $pdo->query("SELECT `id`, `files_json` FROM `employees` WHERE `files_json` LIKE '%uploads%'")->fetchAll(\PDO::FETCH_ASSOC);
        } catch (\Throwable $e) {
            return 0;
        }
        if (!$rows) {
            return 0;
        }
        $uploads = ccrm_uploads_dir();
        $realUploads = realpath($uploads);
        $privateDir = ccrm_employee_private_dir();
        foreach ($rows as $row) {
            $files = json_decode((string)$row['files_json'], true);
            if (!is_array($files)) {
                continue;
            }
            $changed = false;
            foreach ($files as $i => $file) {
                if (!is_array($file)) {
                    continue;
                }
                $url = (string)($file['url'] ?? $file['path'] ?? '');
                if ($url === '' || ccrm_employee_private_key_ok($url)) {
                    continue;
                }
                if (!preg_match('#^/?uploads/(.+)$#', str_replace('\\', '/', $url), $m)) {
                    continue;
                }
                $relative = $m[1];
                $source = realpath($uploads . $relative);
                if ($source === false || $realUploads === false || strncmp($source, $realUploads, strlen($realUploads)) !== 0 || !is_file($source)) {
                    error_log('[ccrm employee files] document of employee ' . $row['id'] . ' is missing on disk, record kept: ' . $url);
                    continue;
                }
                $name = ccrm_employee_private_new_name($relative);
                $target = $privateDir . $name;
                if (!@rename($source, $target)) {
                    if (!@copy($source, $target)) {
                        error_log('[ccrm employee files] could not move ' . $url . ' for employee ' . $row['id']);
                        continue;
                    }
                    @unlink($source);
                }
                $files[$i]['url'] = ccrm_employee_private_prefix() . $name;
                unset($files[$i]['path']);
                $changed = true;
                $moved++;
            }
            if ($changed) {
                $upd = $pdo->prepare("UPDATE `employees` SET `files_json` = ? WHERE `id` = ?");
                $upd->execute([json_encode(array_values($files), JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES), $row['id']]);
            }
        }
        return $moved;
    }

    /** Content type for serving a stored document, from its extension. */
    function ccrm_employee_file_content_type(string $nameOrKey): string {
        $map = [
            'pdf' => 'application/pdf',
            'png' => 'image/png',
            'jpg' => 'image/jpeg',
            'jpeg' => 'image/jpeg',
            'gif' => 'image/gif',
            'webp' => 'image/webp',
            'txt' => 'text/plain; charset=utf-8',
            'doc' => 'application/msword',
            'docx' => 'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
            'xls' => 'application/vnd.ms-excel',
            'xlsx' => 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
            'ppt' => 'application/vnd.ms-powerpoint',
            'pptx' => 'application/vnd.openxmlformats-officedocument.presentationml.presentation',
            'zip' => 'application/zip',
        ];
        $ext = strtolower(pathinfo($nameOrKey, PATHINFO_EXTENSION));
        return $map[$ext] ?? 'application/octet-stream';
    }
}
